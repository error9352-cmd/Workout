create table if not exists public.admin_audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid not null references auth.users(id) on delete cascade,
  action text not null,
  target_type text,
  target_id text,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists admin_audit_log_created_at_idx on public.admin_audit_log(created_at desc);
create index if not exists admin_audit_log_actor_id_idx on public.admin_audit_log(actor_id);
create index if not exists admin_audit_log_action_idx on public.admin_audit_log(action);

alter table public.admin_audit_log enable row level security;

drop policy if exists "admin audit select" on public.admin_audit_log;
create policy "admin audit select"
on public.admin_audit_log
for select to authenticated
using (exists (select 1 from public.profiles p where p.id=auth.uid() and p.role='admin'));

revoke all on table public.admin_audit_log from anon, authenticated;
grant select on public.admin_audit_log to authenticated;

create or replace function public.ap_admin_audit(
  p_action text,
  p_target_type text default null,
  p_target_id text default null,
  p_details jsonb default '{}'::jsonb
)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare new_id bigint;
begin
  if auth.uid() is null then raise exception 'Not authenticated'; end if;
  if not exists (select 1 from public.profiles where id=auth.uid() and role='admin') then
    raise exception 'Admin access required';
  end if;
  insert into public.admin_audit_log(actor_id,action,target_type,target_id,details)
  values(auth.uid(),left(trim(coalesce(p_action,'')),120),left(trim(p_target_type),80),left(trim(p_target_id),200),coalesce(p_details,'{}'::jsonb))
  returning id into new_id;
  return new_id;
end;
$$;

revoke all on function public.ap_admin_audit(text,text,text,jsonb) from public, anon;
grant execute on function public.ap_admin_audit(text,text,text,jsonb) to authenticated;
